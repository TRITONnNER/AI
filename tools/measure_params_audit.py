"""Замер по инварианту 30: сколько параметров не работают и чем это установлено.

Два способа, и они дают разное. **Статика** обходит AST и знает, в каком модуле и в
какой функции взято значение по ключу, — то есть знает путь, а однобокость есть свойство
путей и иначе не устанавливается. **Счётчики в прогоне** видят чтение по вычисленному
ключу, которого статике не видно вовсе, но не знают, с какого пути чтение пришло.

Поэтому диагноз ставит статика, а счётчик её проверяет, и расхождение способов — само по
себе находка. Здесь считается и то, и другое, и покрытие прогона выводится числом: если
прогон читает малую долю схемы, доверять его молчанию нельзя, и это должно быть видно, а
не подразумеваться.

Запуск: `python3 tools/measure_params_audit.py`. Результат — `docs/measurements/
params_audit.json`, по нему рисуются изображения 18 и 19.
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from harness.core.settings import SCHEMA                            # noqa: E402
from harness.params import (Diagnosis, audit, counts, defect_count,  # noqa: E402
                            defects, render_table, runtime_probe)

#: Три последовательные редакции модели путей внутри самой задачи TASK-10, с числом
#: объявленных дефектов на каждой. **Текущим кодом эти числа не воспроизводятся**: они
#: сняты по ходу правки детектора, и восстановить их можно только откатом модели путей.
#: Записаны здесь именно потому, что они и есть главный результат: пять из семи
#: «дефектов» третьей редакции оказались ошибкой детектора, а не кода, и признать это
#: числом важнее, чем показать конечный ноль.
REDACTIONS: tuple[dict[str, object], ...] = (
    {"название": "1: применимо всё ко всем путям",
     "объявлено": 140, "настоящих": 2,
     "почему": "применимость не объявлялась вовсе; 140 из 155 — шум, в котором "
               "размер кадра утонул бы так же, как тонул до детектора"},
    {"название": "2: применимость по группе настроек",
     "объявлено": 27, "настоящих": 2,
     "почему": "у модуля один путь; session.py и core/* обслуживают несколько, и "
               "детектор требовал читателя там, где механизма нет"},
    {"название": "3: модуль обслуживает несколько путей",
     "объявлено": 7, "настоящих": 2,
     "почему": "instances.py числился синтетическим, хотя складывает Testimony в "
               "BeliefStore; сторож числился агентским, хотя живёт на инъекции"},
    {"название": "4: применимость объявлена в схеме",
     "объявлено": 2, "настоящих": 2,
     "почему": "остались только настоящие: frame_format читался лишь живым путём, "
               "macro_max_length — только печатью"},
)


def main() -> int:
    findings = audit()
    with tempfile.TemporaryDirectory(prefix="harness-params-") as d:
        seen = runtime_probe(steps=40, root=Path(d) / "session")

    with_runtime = audit(runtime=seen)
    # Два расхождения — не одно, и смешивать их нельзя. «Статика молчит, прогон читает»
    # означает ошибку способа: ключ вычисляется. «Статика видит, прогон не читает»
    # означает всего лишь путь, который прогон не проходил, и таких большинство, потому
    # что прогон короткий и синтетический. Одно число на оба вида создало бы тревогу на
    # сто пятнадцать строк там, где находок ноль.
    blind = [f.key for f in with_runtime if f.static_blind]
    unvisited = [f.key for f in with_runtime if f.disagreement and not f.static_blind]

    data = {
        "всего_настроек": len(SCHEMA),
        "диагнозы": counts(findings),
        "дефектов": defect_count(findings),
        "дефекты": [f.as_dict() for f in defects(findings)],
        "редакции": list(REDACTIONS),
        "прогон": {
            "шагов": 40,
            "прочитано_ключей": len({k for k, v in seen.items() if v}),
            "обращений": sum(seen.values()),
            "статика_слепа": len(blind),
            "статика_слепа_на": blind,
            "путь_не_пройден": len(unvisited),
            "почему_не_полное": "прогон синтетический и агентский: живой путь требует "
                                "экрана и звука. Подсунуть сюда заглушку было бы хуже "
                                "всего — счётчик показал бы чтения, которых на "
                                "настоящей машине не случилось",
        },
        "единица_независимости": "настройка",
    }
    out = ROOT / "docs" / "measurements" / "params_audit.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")

    print(render_table(findings, only_defects=True))
    print()
    print(f"настроек в схеме: {len(SCHEMA)}")
    print(f"прогон со счётчиками: прочитано {data['прогон']['прочитано_ключей']} "
          f"ключей, {data['прогон']['обращений']} обращений")
    print(f"статика слепа (ключ вычисляется): {len(blind)}")
    print(f"путь не пройден прогоном: {len(unvisited)} — не дефект, а неполнота "
          "прогона")
    print(f"записано: {out.relative_to(ROOT)}")
    return 0 if counts(findings)[str(Diagnosis.OK)] > 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
