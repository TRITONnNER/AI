# ---------------------------------------------------------------------------
#
# Зачем отдельным разделом. Состояние вехи должно читаться без чтения истории
# коммитов, а таблица «Части» на это не отвечает: она про модули, а веха — про
# требования. Модуль может быть написан и покрыт тестами, а требование при этом не
# проверено ни одним замером: тест говорит «код делает то, что задумано», замер —
# «задуманное происходит в мире».
#
# Градаций три, и средняя — не полумера, а самый частый случай:
#
#   measured  — проверено замером. Обязательно указано, каким и на чём;
#   unmeasured— есть, работает, но проверенного числа за этим нет. Сюда же попадает
#               «замер выполнен и не разрешился»: замер, который не различил
#               гипотезы, проверкой не является, и различать его от «не мерено» в
#               градации нельзя — иначе получится третье состояние, читаемое как
#               половина проверки. Что именно произошло, сказано в колонке «чем»;
#   absent    — нет совсем.
#
# `basis` — синтетика или живое. Различие главное из всех: на живом экране не
# проверено **ничего**, и это выводится отдельной строкой, а не выводится читателем
# из таблицы.
