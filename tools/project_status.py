def _n_settings() -> int:
    """Сколько настроек в схеме. Считается, а не пишется рукой.

    Здесь стояло «140 настроек» литералом, и к моменту TASK-10 их стало 155. Число,
    нарисованное рукой в генераторе отчёта, — то же самое, что порог, нарисованный рукой
    в аналитическом скрипте (инвариант 23): оно не сравнимо между прогонами и расходится
    с кодом молча. Ровно от этого `docs/STATUS.md` и генерируется.
    """
    from harness.core.settings import SCHEMA

    return len(SCHEMA)


