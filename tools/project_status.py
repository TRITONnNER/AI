#: Градации в порядке убывания силы утверждения и как их печатать.
GRADES: tuple[tuple[str, str], ...] = (
    ("measured", "проверено замером"),
    ("unmeasured", "есть, но не мерено"),
    ("absent", "нет совсем"),
)


def m3_summary() -> dict[str, object]:
    """Состояние М3 по трём градациям плюс главное число — сколько на живом."""
    by_grade = {g: sum(1 for i in M3_ITEMS if i["grade"] == g) for g, _ in GRADES}
    live = sum(1 for i in M3_ITEMS
               if i["grade"] == "measured" and i["basis"] == "живое")
    unknown = [i["grade"] for i in M3_ITEMS
               if i["grade"] not in dict(GRADES)]
    if unknown:
        raise SystemExit(f"неизвестная градация: {unknown}. Набор закрыт: "
                         f"{[g for g, _ in GRADES]}")
    return {"items": list(M3_ITEMS), "by_grade": by_grade,
            "total": len(M3_ITEMS), "measured_on_live": live}



