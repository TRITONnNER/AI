"""Единица независимости метрики. Инвариант 22.

Основание — не теория, а провал. В замере доли дошедших планов 1913 «наблюдений»
оказались 94 маршрутами: одно и то же ребро пересчитывалось двадцать раз, и на
таких данных закономерность получается **на любых** входных данных. Вывод из-за
этого был неверен дважды подряд, причём второй раз — уже в отчёте, который прямо
исправлял первый.

Отсюда правило: **всякая метрика объявляет свою единицу независимости, и `n`
считает единицы, а не события.** Метрика без объявленной единицы не создаётся.

## Почему нельзя просто «быть аккуратным»

Потому что ошибка невидима в результате. Доля 5/65 против 56/56 выглядит одинаково
убедительно и когда за ней 121 независимый маршрут, и когда за ней два ребра,
пересчитанных по тридцать раз. Различить это по числу нельзя — только по тому, что
объявлено единицей. Значит объявление обязано быть в типе, а не в добросовестности.

## Два разных вида чисел

Смешение этих двух видов и есть источник путаницы.

**Счёт** — «записей 412», «выходов 16». Утверждение о том, что пересчитано, и
никакого вывода за пределы пересчитанного оно не делает. Независимость тут не
заявляется, и заявлять её незачем.

**Доля, среднее, разброс** — «доходит 91 %», «IoU 0.97». Такое число утверждает
нечто о случаях, которых в выборке не было, и потому опирается на независимость
единиц. Здесь единицу объявить обязательно, и `n` обязано быть числом единиц.

## Запрещённые единицы

Пиксель и кадр не бывают единицей ни для какого утверждения. Соседние пиксели
одного кадра почти всегда одного класса, соседние кадры одной сессии отличаются на
доли процента, а их миллионы и тысячи соответственно — поэтому «n = 2 000 000
пикселей» означает не точность, а раздутый знаменатель. Отказ здесь громкий: это
самая частая форма псевдорепликации в измерениях по изображениям.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum
from typing import Any, Iterable, Mapping


class UnitError(ValueError):
    pass


class Aggregate(StrEnum):
    """Что за число. От этого зависит, обязана ли метрика заявлять независимость."""

    COUNT = "count"      # сколько чего-то было; вывода за пределы выборки нет
    SHARE = "share"      # доля; заявляет независимость единиц
    MEAN = "mean"        # среднее по единицам
    SPREAD = "spread"    # разброс по единицам


#: Единицы, которые бывают независимыми, и почему. Набор закрыт: новая единица —
#: это новое утверждение о том, что варьируется независимо, и оно должно быть
#: обосновано здесь, а не в вызывающем коде.
UNITS: Mapping[str, str] = {
    "запись": "одна запись журнала. Годится для счёта, но для доли — только если "
              "утверждение и правда о записях, а не о том, что за ними стоит",
    "прогон": "один прогон (мир, сид) от начала до конца. Внутри прогона всё "
              "зависимо: вторая цель существует потому, что первая что-то изменила",
    "домен": "отдельный генератор мира со своей логикой обрамления. Единица для "
             "утверждений вида «метод доменно-независим»",
    "генератор": "весь набор синтетических миров как одно допущение. Если детектор "
                 "и генератор писались вместе, независимых единиц ровно одна",
    "сессия": "одна записанная сессия. Кадры внутри неё не независимы, сессии — да",
    "маршрут": "различная цепочка (место, действие) → место. Единица для доли "
               "дошедших планов: попытка не годится, потому что приход "
               "инкрементирует силу ребра и попытки на одном ребре зависимы",
    "выход": "один выход устройства ввода. Внутри одного мира выходы разделяют его "
             "проводку, поэтому для утверждений о методе единица — прогон, не выход",
    "место": "один узел графа мест",
    "цель": "одна цель. Для доли выполненных годится только между прогонами: внутри "
            "прогона цели выведены из одной карты тела",
    "сегмент": "один сегмент уровней 1–3",
    "линия": "одна линия журнала",
}

#: Единицы, которые не бывают независимыми никогда, и что вместо них.
NOT_INDEPENDENT: Mapping[str, str] = {
    "пиксель": "соседние пиксели одного кадра почти всегда одного класса, а их "
               "миллионы. Правильная единица — сцена, прогон или сессия",
    "кадр": "соседние кадры одной сессии отличаются на доли процента. Правильная "
            "единица — сессия или прогон",
    "событие": "«событие» — это то, что мы считаем, а не то, что варьируется "
               "независимо. Назовите, что именно варьируется",
    "попытка": "попытки на одном и том же объекте зависимы: именно на этом "
               "сломался замер доли дошедших планов. Назовите объект — маршрут, "
               "прогон, сессию",
}


@dataclass(frozen=True, slots=True)
class Independence:
    """Объявление единицы независимости и числа единиц.

    `n` — сколько **единиц**, а не событий. Для счёта `n` совпадает с самим числом
    и это не совпадение: счёт и есть перечисление своих единиц.
    """

    unit: str
    n: int | None
    aggregate: Aggregate = Aggregate.COUNT
    note: str = ""

    def __post_init__(self) -> None:
        if not self.unit:
            raise UnitError(
                "метрика без объявленной единицы независимости не создаётся "
                "(инвариант 22). Назовите, что именно варьируется независимо")
        if self.unit in NOT_INDEPENDENT:
            raise UnitError(
                f"{self.unit!r} не бывает единицей независимости: "
                f"{NOT_INDEPENDENT[self.unit]}")
        if self.unit not in UNITS:
            raise UnitError(
                f"неизвестная единица {self.unit!r}. Набор закрыт: {sorted(UNITS)}. "
                "Новая единица — это новое утверждение о том, что варьируется "
                "независимо, и обосновывается она в units.py, а не на месте вызова")
        if self.n is not None and self.n < 0:
            raise UnitError(f"единиц не может быть {self.n}")
        if self.aggregate is not Aggregate.COUNT and self.n is None:
            raise UnitError(
                f"{self.aggregate} по единице {self.unit!r} без числа единиц. "
                "Доля без знаменателя в единицах — это и есть псевдорепликация: по "
                "ней не видно, стоит за числом сто наблюдений или два. Если единиц "
                "не было вовсе, это n=0, и тогда самого числа быть не должно")

    @property
    def is_claim(self) -> bool:
        """Делает ли метрика вывод за пределы пересчитанного."""
        return self.aggregate is not Aggregate.COUNT

    @property
    def empty(self) -> bool:
        """Единиц нет вовсе. Тогда числа быть не должно — только причина."""
        return self.n == 0

    @property
    def thin(self) -> bool:
        """Единиц слишком мало, чтобы доля что-то значила. Не ошибка, но пометка."""
        return self.is_claim and self.n is not None and 0 < self.n < 3

    def text(self) -> str:
        if not self.is_claim:
            return f"счёт в единицах «{self.unit}»"
        if self.empty:
            return f"единиц «{self.unit}» не было — считать нечего"
        thin = ", единиц мало" if self.thin else ""
        return f"{self.aggregate} по {self.n} единиц «{self.unit}»{thin}"

    def as_dict(self) -> dict[str, Any]:
        return {"unit": self.unit, "n": self.n, "aggregate": str(self.aggregate),
                "is_claim": self.is_claim, "thin": self.thin, "note": self.note}

    @classmethod
    def from_dict(cls, d: Mapping[str, Any]) -> Independence:
        return cls(str(d["unit"]), None if d.get("n") is None else int(d["n"]),
                   Aggregate(d.get("aggregate", "count")), str(d.get("note", "")))


# --- удобные конструкторы, чтобы на месте вызова читалось одной строкой ------


def count(unit: str, n: int | None = None, note: str = "") -> Independence:
    """Счёт. Независимость не заявляется, потому что вывода за выборку нет."""
    return Independence(unit, n, Aggregate.COUNT, note)


def share(unit: str, n: int | None, note: str = "") -> Independence:
    """Доля. `n` — число независимых единиц в знаменателе, не число событий."""
    return Independence(unit, n, Aggregate.SHARE, note)


def mean(unit: str, n: int | None, note: str = "") -> Independence:
    return Independence(unit, n, Aggregate.MEAN, note)


def spread(unit: str, n: int | None, note: str = "") -> Independence:
    return Independence(unit, n, Aggregate.SPREAD, note)


def reduce_to_units(items: Iterable[Any], key: Any) -> tuple[int, int]:
    """Сколько было событий и сколько осталось единиц. Возвращает `(события, единицы)`.

    Ровно та операция, которой не хватало в замере планов: события считались за
    единицы. Отношение первого ко второму — коэффициент псевдорепликации, и его
    полезно печатать рядом с числом: ×20 означает, что доля посчитана по выборке в
    двадцать раз меньшей, чем кажется.
    """
    seen: set[Any] = set()
    total = 0
    for item in items:
        total += 1
        seen.add(key(item))
    return total, len(seen)


def pseudoreplication(events: int, units: int) -> float:
    """Во сколько раз выборка меньше, чем кажется по числу событий."""
    return events / units if units else float("inf")
