BY_KEY: dict[str, Setting] = {}
for _setting in SCHEMA:
    if _setting.key in BY_KEY:
        raise SchemaError(f"настройка {_setting.key} объявлена дважды")
    _setting.check(_setting.default)          # значение по умолчанию тоже проверяется
    BY_KEY[_setting.key] = _setting
del _setting

GROUPS: tuple[str, ...] = tuple(dict.fromkeys(s.group for s in SCHEMA))


def defaults(structural: bool) -> dict[str, Any]:
    """Значения по умолчанию одной из двух групп."""
    return {s.key: s.default for s in SCHEMA if s.structural is structural}


def validate(parameters: Mapping[str, Any], structural: Mapping[str, Any]) -> None:
    """Проверить набор настроек против схемы. Падает на первом расхождении.

    Ловит три ошибки, каждая из которых иначе всплывает поздно и невнятно:
    неизвестная ручка (опечатка в имени тихо не сработала бы), значение вне
    границ, и — самое дорогое — настройка, попавшая не в ту группу.
    """
    for group_name, values, want_structural in (
            ("parameters", parameters, False), ("structural", structural, True)):
        for key, value in values.items():
            setting = BY_KEY.get(key)
            if setting is None:
                near = [k for k in BY_KEY if k.startswith(key[:6])]
                hint = f"; похожие: {sorted(near)[:3]}" if near else ""
                raise SchemaError(f"{group_name}: неизвестная настройка {key!r}{hint}")
            if setting.structural is not want_structural:
                right = "structural" if setting.structural else "parameters"
                raise SchemaError(
                    f"{key} объявлена как {right}, а лежит в {group_name}. "
                    "Настройка, меняющая форму опыта, обязана форкать журнал")
            setting.check(value)

    missing = {s.key for s in SCHEMA} - set(parameters) - set(structural)
    if missing:
        raise SchemaError(
            f"нет настроек: {sorted(missing)}. Профиль обязан быть полным: "
            "недостающая ручка означает захардкоженную константу где-то в коде")


def table(group: str | None = None) -> list[dict[str, Any]]:
    """Схема как таблица — для CLI, пульта и документации."""
    return [
        {"key": s.key, "group": s.group, "kind": s.kind, "unit": s.unit,
         "default": s.default, "block": "Б" if s.structural else "А",
         "range": _range_text(s), "note": s.note}
        for s in SCHEMA if group is None or s.group == group
    ]


def _range_text(s: Setting) -> str:
    if s.choices:
        return " | ".join(s.choices)
    if s.lo is None and s.hi is None:
        return "—"
    lo = "−∞" if s.lo is None else _num(s.lo)
    hi = "+∞" if s.hi is None else _num(s.hi)
    return f"{lo}…{hi}"


def _num(v: float) -> str:
    return str(int(v)) if float(v).is_integer() else str(v)


def structural_keys() -> frozenset[str]:
    return frozenset(s.key for s in SCHEMA if s.structural)


def describe(key: str) -> str:
    s = BY_KEY.get(key)
    if s is None:
        raise SchemaError(f"нет настройки {key!r}")
    block = "Блок Б, форкает журнал" if s.structural else "Блок А, меняется на ходу"
    return (f"{s.key} = {s.default} {s.unit} [{s.group}; {block}; "
            f"диапазон {_range_text(s)}]\n  {s.note}")
