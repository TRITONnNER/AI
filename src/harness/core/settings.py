"""Схема настроек: каждая ручка объявлена, а не заведена по случаю.

Правило проекта: «все настройки живут в одном объекте `Profile`, захардкоженных
констант поведения быть не должно». Одного словаря для этого мало: словарь не
знает единиц измерения, границ, смысла и того, форкает ли ручка журнал. Поэтому
здесь схема — по строке на настройку, — а `Profile` остаётся машинерией хешей и
ветвления.

Что даёт схема:

- **Единицы обязательны.** Не «длительность», а «мс». Не «память», а «МиБ».
- **Границы проверяются.** `capture_fps = -5` не доедет до записи.
- **`parameter` или `structural` объявлено при настройке**, а не решается в
  момент использования. Ошибиться в эту сторону дорого: параметр, который на
  самом деле меняет форму данных, смешает несравнимый опыт в одной ветке.
- **Таблица настроек генерируется** из схемы: `harness profile --schema`, а
  значит документация не расходится с кодом.

Разделение простое и проверяемое вопросом «изменится ли форма или смысл
накопленного опыта, если повернуть эту ручку на ходу?». Изменится — `structural`.
Частота захвата не меняет: записи останутся сравнимыми. Формат кадра меняет.
Отключение хеширования текста меняет — агент внезапно получит читаемый язык.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum
from typing import Any, Iterable, Literal, Mapping

Kind = Literal["bool", "int", "float", "str"]


class RunPath(StrEnum):
    """Путь исполнения, на котором настройка может что-то изменить.

    Словарь путей живёт рядом со схемой, а не в детекторе (`harness.params`), потому
    что применимость — это **объявление схемы**, а не вывод анализатора. Детектор
    только сверяет объявленное с найденными читателями (инвариант 30).
    """

    LIVE = "живая запись"          # захват экрана, звук, инъекция ввода
    SYNTHETIC = "синтетика"        # генератор корпуса, миры с известной истиной
    AGENT = "агентский стек"       # восприятие, поведение, модель мира
    REPORT = "печать отчёта"       # читателем не считается


class SchemaError(ValueError):
    """Схема или значение не сходятся."""


@dataclass(frozen=True, slots=True)
class Setting:
    key: str
    kind: Kind
    default: bool | int | float | str
    unit: str                        # «мс», «МиБ», «Гц», «доля», «—»
    group: str                       # для таблиц и для пульта
    structural: bool                 # True → форкает журнал
    note: str
    lo: float | None = None
    hi: float | None = None
    choices: tuple[str, ...] = ()
    # Настройка объявлена, но её пока никто не читает: механизм, который будет ею
    # управлять, не написан. Отмечать это обязательно — объявленная и никем не
    # читаемая ручка обещает поведение, которого нет, и это ровно та тихая ложь,
    # которую проект запрещает. Тест `test_every_setting_is_either_used_or_planned`
    # не даёт добавить такую ручку молча.
    planned: str = ""
    # К какому источнику применима настройка. По умолчанию к любому.
    #
    # Профиль остаётся **одним** объектом с одним хешем, и настройки синтетического
    # мира лежат в живой записи тоже. Решение принято сознательно (TASK-09, часть 4):
    # профиль — это идентичность эксперимента, и выбрасывать из него ключи по
    # источнику значило бы, что `profile_hash` в разных сессиях считается по разным
    # словарям, то есть перестаёт быть сравнимым. Хуже того, запись потеряла бы
    # способность описывать себя: по ней стало бы нельзя отличить «этой настройки
    # тогда не было» от «эта настройка была неприменима».
    #
    # Вред, который задача называет, — ложные различия при сверке двух живых
    # профилей — снимается не выбрасыванием, а **подписью**: `Profile.diff` помечает
    # такие строки, и видно, что различие на живую запись повлиять не могло.
    #
    # Значения — из `RunPath`. Пустой кортеж означает «по группе»: применимость
    # группы объявлена в `harness.params.GROUP_APPLIES`, и большинству настроек этого
    # достаточно. Заполнять здесь нужно те, что отличаются от своей группы — иначе
    # детектор мёртвых параметров спросит читателя на пути, которого у механизма нет,
    # и объявит однобоким работающий параметр.
    applies_to: tuple[str, ...] = ()

    def check(self, value: Any) -> bool | int | float | str:
        """Проверить значение и привести к объявленному типу."""
        if self.kind == "bool":
            if not isinstance(value, bool):
                raise SchemaError(f"{self.key}: ожидался bool, пришло {value!r}")
            return value
        if self.kind == "int":
            if isinstance(value, bool) or not isinstance(value, int):
                raise SchemaError(f"{self.key}: ожидалось целое, пришло {value!r}")
            v: int | float = value
        elif self.kind == "float":
            if isinstance(value, bool) or not isinstance(value, (int, float)):
                raise SchemaError(f"{self.key}: ожидалось число, пришло {value!r}")
            v = float(value)
        else:
            if not isinstance(value, str):
                raise SchemaError(f"{self.key}: ожидалась строка, пришло {value!r}")
            if self.choices and value not in self.choices:
                raise SchemaError(
                    f"{self.key}: {value!r} не из набора {self.choices}")
            return value
        if self.lo is not None and v < self.lo:
            raise SchemaError(f"{self.key}: {v} меньше минимума {self.lo} ({self.unit})")
        if self.hi is not None and v > self.hi:
            raise SchemaError(f"{self.key}: {v} больше максимума {self.hi} ({self.unit})")
        return int(v) if self.kind == "int" else float(v)


def _s(key: str, kind: Kind, default: Any, unit: str, group: str, note: str,
       *, structural: bool = False, lo: float | None = None, hi: float | None = None,
       choices: Iterable[str] = (), planned: str = "",
       applies_to: Iterable[str] = ()) -> Setting:
    return Setting(key, kind, default, unit, group, structural, note, lo, hi,
                   tuple(choices), planned, tuple(str(x) for x in applies_to))




