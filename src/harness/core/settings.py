"""Схема настроек: каждая ручка объявлена, а не заведена по случаю.

Правило проекта: «все настройки живут в одном объекте `Profile`, захардкоженных
констант поведения быть не должно». Одного словаря для этого мало: словарь не
знает единиц измерения, границ, смысла и того, форкает ли ручка журнал. Поэтому
здесь схема — по строке на настройку, — а `Profile` остаётся машинерией хешей и
ветвления.

Что даёт схема:

- **Единицы обязательны.** Не «длительность», а «мс». Не «память», а «МиБ».
- **Границы проверяются.** `capture_fps = -5` не доедет до записи.
- **`parameter` или `structural` объявлено при настройке**, а не решается в
  момент использования. Ошибиться в эту сторону дорого: параметр, который на
  самом деле меняет форму данных, смешает несравнимый опыт в одной ветке.
- **Таблица настроек генерируется** из схемы: `harness profile --schema`, а
  значит документация не расходится с кодом.

Разделение простое и проверяемое вопросом «изменится ли форма или смысл
накопленного опыта, если повернуть эту ручку на ходу?». Изменится — `structural`.
Частота захвата не меняет: записи останутся сравнимыми. Формат кадра меняет.
Отключение хеширования текста меняет — агент внезапно получит читаемый язык.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Iterable, Literal, Mapping

Kind = Literal["bool", "int", "float", "str"]


class SchemaError(ValueError):
    """Схема или значение не сходятся."""


@dataclass(frozen=True, slots=True)
class Setting:
    key: str
    kind: Kind
    default: bool | int | float | str
    unit: str                        # «мс», «МиБ», «Гц», «доля», «—»
    group: str                       # для таблиц и для пульта
    structural: bool                 # True → форкает журнал
    note: str
    lo: float | None = None
    hi: float | None = None
    choices: tuple[str, ...] = ()

    def check(self, value: Any) -> bool | int | float | str:
        """Проверить значение и привести к объявленному типу."""
        if self.kind == "bool":
            if not isinstance(value, bool):
                raise SchemaError(f"{self.key}: ожидался bool, пришло {value!r}")
            return value
        if self.kind == "int":
            if isinstance(value, bool) or not isinstance(value, int):
                raise SchemaError(f"{self.key}: ожидалось целое, пришло {value!r}")
            v: int | float = value
        elif self.kind == "float":
            if isinstance(value, bool) or not isinstance(value, (int, float)):
                raise SchemaError(f"{self.key}: ожидалось число, пришло {value!r}")
            v = float(value)
        else:
            if not isinstance(value, str):
                raise SchemaError(f"{self.key}: ожидалась строка, пришло {value!r}")
            if self.choices and value not in self.choices:
                raise SchemaError(
                    f"{self.key}: {value!r} не из набора {self.choices}")
            return value
        if self.lo is not None and v < self.lo:
            raise SchemaError(f"{self.key}: {v} меньше минимума {self.lo} ({self.unit})")
        if self.hi is not None and v > self.hi:
            raise SchemaError(f"{self.key}: {v} больше максимума {self.hi} ({self.unit})")
        return int(v) if self.kind == "int" else float(v)


def _s(key: str, kind: Kind, default: Any, unit: str, group: str, note: str,
       *, structural: bool = False, lo: float | None = None, hi: float | None = None,
       choices: Iterable[str] = ()) -> Setting:
    return Setting(key, kind, default, unit, group, structural, note, lo, hi,
                   tuple(choices))


